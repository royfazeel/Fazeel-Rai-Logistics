/** Encode approved original equipment photos without cropping or enlarging.
 * Masters and generation prompts are retained in output/seo-sep28/.
 * Generated AVIF/WebP files and their manifest are committed for deployment.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const sharp = createRequire(import.meta.url)('sharp');
const root = fileURLToPath(new URL('../', import.meta.url));
const widths = [480, 768, 1200, 1536];
const photos = {
  'dry-van': 'Red semi tractor with a white enclosed dry van trailer at a freight terminal',
  reefer: 'Red semi tractor with a white refrigerated trailer and front-mounted refrigeration unit',
  flatbed: 'Red semi tractor with an empty single-level flatbed trailer',
  'box-truck': 'Red straight box truck with a white enclosed cargo body at a warehouse',
  'power-only': 'Red sleeper-cab semi tractor with an exposed fifth wheel and no trailer attached',
  'step-deck': 'Red semi tractor with an empty step deck trailer showing its raised front and lower main deck',
  hotshot: 'Red heavy-duty pickup towing a gooseneck flatbed hotshot trailer',
  'cargo-van': 'Red standard-roof cargo van with enclosed side panels at a loading warehouse',
  'sprinter-van': 'Red high-roof long-wheelbase Sprinter-style cargo van at a freight facility',
  conestoga: 'Red semi tractor with a rolling-tarp Conestoga flatbed trailer',
  'rgn-lowboy': 'Red heavy-haul tractor with a detachable-gooseneck lowboy trailer and low center deck',
  'car-hauler': 'Red semi tractor with an open two-level car-hauler trailer carrying passenger vehicles',
  tanker: 'Red semi tractor with a cylindrical stainless-steel tanker trailer',
  'dump-truck': 'Red four-axle dump truck with its open-top steel body lowered at an aggregate yard',
  'curtain-side': 'Red semi tractor with a curtain-side trailer showing its fixed roof and sliding side curtain',
};
await mkdir(`${root}public/images/equipment`, { recursive: true });
const manifest = {};
const results = [];
for (const [slug, alt] of Object.entries(photos)) {
  const source = `${root}output/seo-sep28/equipment-masters/${slug}.png`;
  const metadata = await sharp(source).metadata();
  const url = (width, format) => `/images/equipment/${slug}-${width}-v1.${format}`;
  for (const width of widths) {
    for (const format of ['avif', 'webp']) {
      const pipeline = sharp(source).resize({ width, withoutEnlargement: true });
      const encoded = format === 'avif' ? pipeline.avif({ quality: 65, effort: 5, chromaSubsampling: '4:4:4' }) : pipeline.webp({ quality: 85, effort: 5 });
      const info = await encoded.toFile(`${root}public${url(width, format)}`);
      results.push({ slug, width, format, bytes: info.size });
    }
  }
  manifest[slug] = { alt, width: 1200, height: Math.round(1200 * metadata.height / metadata.width), src: url(1200, 'webp'), avifSrc: url(1200, 'avif'),
    avifSrcSet: widths.map(width => `${url(width, 'avif')} ${width}w`).join(', '),
    webpSrcSet: widths.map(width => `${url(width, 'webp')} ${width}w`).join(', ') };
}
await writeFile(`${root}src/lib/equipment-images.ts`, `// Generated by scripts/optimize-equipment-images.mjs.\nexport type EquipmentImage = { alt: string; width: number; height: number; src: string; avifSrc: string; avifSrcSet: string; webpSrcSet: string };\nexport const EQUIPMENT_IMAGES: Record<string, EquipmentImage> = ${JSON.stringify(manifest, null, 2)};\n`);
await writeFile(`${root}output/seo-sep28/equipment-image-sizes.json`, JSON.stringify(results, null, 2));
console.log(JSON.stringify({ photos: Object.keys(manifest).length, variants: results.length, totalBytes: results.reduce((n, r) => n + r.bytes, 0), max768AvifBytes: Math.max(...results.filter(r => r.width === 768 && r.format === 'avif').map(r => r.bytes)) }));
