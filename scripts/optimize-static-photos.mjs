#!/usr/bin/env node
/**
 * Build responsive versions of the two locally hosted highway photographs.
 * Run: node scripts/optimize-static-photos.mjs
 *
 * Full-frame resizing preserves the existing CSS object-cover crops. Quality
 * matches the homepage HeroPhoto assets. No image is enlarged or fetched.
 * Increment VERSION when changing a master, encoding, or output dimensions.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const VERSION = 'v1';
const WEBP_QUALITY = 85;
const AVIF_QUALITY = 65;
const directory = fileURLToPath(new URL('../public/images/photos/', import.meta.url));
const variants = [
  { name: 'hero-highway', width: 1920, height: 1080, widths: [480, 768, 1200, 1600, 1920] },
  { name: 'cta-highway', width: 1600, height: 900, widths: [480, 768, 1200, 1600] },
];

await mkdir(directory, { recursive: true });
const manifest = {};
const results = [];
for (const variant of variants) {
  const original = `/video/${variant.name}.jpg`;
  const source = fileURLToPath(new URL(`../public${original}`, import.meta.url));
  const metadata = await sharp(source).metadata();
  if (metadata.width !== variant.width || metadata.height !== variant.height) {
    throw new Error(`${original} dimensions changed; review the sizes and increment VERSION.`);
  }
  const url = (width, format) => `/images/photos/${variant.name}-${width}-${VERSION}.${format}`;
  for (const width of variant.widths) {
    const resized = sharp(source).resize({ width, withoutEnlargement: true });
    for (const format of ['webp', 'avif']) {
      const encoded = format === 'webp'
        ? resized.clone().webp({ quality: WEBP_QUALITY, effort: 6 })
        : resized.clone().avif({ quality: AVIF_QUALITY, effort: 6, chromaSubsampling: '4:4:4' });
      const filename = `${variant.name}-${width}-${VERSION}.${format}`;
      const info = await encoded.toFile(`${directory}/${filename}`);
      results.push({ filename, width: info.width, height: info.height, bytes: info.size });
    }
  }
  manifest[original] = {
    width: variant.width,
    height: variant.height,
    src: url(1200, 'webp'),
    avifSrc: url(1200, 'avif'),
    webpSrcSet: variant.widths.map(width => `${url(width, 'webp')} ${width}w`).join(', '),
    avifSrcSet: variant.widths.map(width => `${url(width, 'avif')} ${width}w`).join(', '),
  };
}
const manifestPath = fileURLToPath(new URL('../src/lib/static-photo-assets.ts', import.meta.url));
await writeFile(manifestPath, `// Generated by scripts/optimize-static-photos.mjs. Do not edit by hand.\nexport const STATIC_PHOTOS = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type StaticPhotoSource = keyof typeof STATIC_PHOTOS;\n`);
console.log(JSON.stringify({ version: VERSION, quality: { webp: WEBP_QUALITY, avif: AVIF_QUALITY }, variants: results }, null, 2));
